<?php

$list = fn (?string $value): array => array_values(array_filter(array_map(trim(...), explode(',', (string) $value))));

return [

    /*
    |--------------------------------------------------------------------------
    | Speech (Phonon)
    |--------------------------------------------------------------------------
    |
    | Speech is generated by Gradium's Phonon text-to-speech models, served by
    | ptts-openai-server. Each server loads one checkpoint (PTTS_MODEL), so
    | run one server per model and list their URLs, separated by commas.
    | The audio studio offers every server it can reach, by model name.
    |
    */

    'speech' => [
        'servers' => $list(env('PHONON_URLS', 'http://phonon:8880')),
        'timeout' => (int) env('PHONON_TIMEOUT', 120),
        'max_characters' => 4096,
    ],

    /*
    |--------------------------------------------------------------------------
    | Music (MusicGen)
    |--------------------------------------------------------------------------
    |
    | Music is generated by Meta's MusicGen, run by the small service in
    | services/musicgen. It keeps one model in memory; the studio can load
    | any of the models listed here, and loads one first if it must.
    |
    */

    'music' => [
        'url' => env('MUSICGEN_URL', 'http://musicgen:8000'),
        'model' => env('MUSICGEN_MODEL', 'facebook/musicgen-small'),
        'models' => $list(env('MUSICGEN_MODELS', 'facebook/musicgen-small,facebook/musicgen-medium,facebook/musicgen-large,facebook/musicgen-stereo-small,facebook/musicgen-stereo-medium')),
        'max_seconds' => (int) env('MUSICGEN_MAX_SECONDS', 30),
        'timeout' => (int) env('MUSICGEN_TIMEOUT', 1200),
    ],

    /*
    |--------------------------------------------------------------------------
    | MIDI (Llama 3)
    |--------------------------------------------------------------------------
    |
    | MIDI is composed by a language model, Llama 3 through Ollama by
    | default, which writes the notes of each stem as structured output.
    | The studio turns them into a Standard MIDI File.
    |
    */

    'midi' => [
        'provider' => env('AUDIO_MIDI_PROVIDER', env('AI_PROVIDER', 'ollama')),
        'model' => env('AUDIO_MIDI_MODEL', 'llama3'),
        'max_bars' => 32,
        'max_tracks' => 8,
        'max_notes' => 2000,
        'timeout' => (int) env('AUDIO_MIDI_TIMEOUT', 300),
    ],

    /*
    |--------------------------------------------------------------------------
    | Vocals (DiffSinger)
    |--------------------------------------------------------------------------
    |
    | Sung vocals: a language model (the MIDI model, Llama 3 by default)
    | writes lyrics and their melody, the app writes them as a DiffSinger
    | score (.ds file) using the voice's phoneme dictionary, and the service
    | in services/diffsinger sings it with the voice you choose.
    |
    */

    'singing' => [
        'url' => env('DIFFSINGER_URL', 'http://diffsinger:8000'),
        'voice' => env('DIFFSINGER_VOICE'),
        'max_bars' => 32,
        'max_lines' => 16,
        'timeout' => (int) env('DIFFSINGER_TIMEOUT', 900),
        'dictionary_cache_seconds' => 3600,
    ],

    /*
    |--------------------------------------------------------------------------
    | Storage
    |--------------------------------------------------------------------------
    */

    'disk' => env('AUDIO_DISK', 'local'),

    'library_size' => 50,

];
